ALTER TABLE library_books
  ADD COLUMN IF NOT EXISTS isbn VARCHAR(32) NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS publisher VARCHAR(160) NOT NULL DEFAULT 'Academic Press',
  ADD COLUMN IF NOT EXISTS publication_year INTEGER NOT NULL DEFAULT 2020,
  ADD COLUMN IF NOT EXISTS call_number VARCHAR(64) NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS total_copies INTEGER NOT NULL DEFAULT 1,
  ADD COLUMN IF NOT EXISTS available_copies INTEGER NOT NULL DEFAULT 1,
  ADD COLUMN IF NOT EXISTS borrowed_copies INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS location VARCHAR(80) NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS status VARCHAR(32) NOT NULL DEFAULT 'Available',
  ADD COLUMN IF NOT EXISTS cover_url TEXT,
  ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW();

CREATE UNIQUE INDEX IF NOT EXISTS idx_library_books_isbn
  ON library_books (isbn)
  WHERE isbn <> '';
